/**
 * Get current active language.
 * Default is 'en' (English) if none is selected.
 */
function getCurrentLang() {
  const saved = localStorage.getItem('silk_road_lang');
  if (saved && TRANSLATIONS[saved]) {
    return saved;
  }
  return 'en'; // DEFAULT
}

/**
 * Translate a key with optional fallback.
 */
function t(key, fallback = '') {
  const lang = getCurrentLang();
  if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key] !== undefined) {
    return TRANSLATIONS[lang][key];
  }
  if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key] !== undefined) {
    return TRANSLATIONS['en'][key];
  }
  return fallback || key;
}

/**
 * Switch language and apply translations to the DOM
 */
function setLanguage(lang) {
  if (!TRANSLATIONS[lang]) lang = 'en';
  localStorage.setItem('silk_road_lang', lang);

  const langConfig = SUPPORTED_LANGS.find(l => l.code === lang) || SUPPORTED_LANGS[0];
  document.documentElement.lang = lang;
  document.documentElement.dir = langConfig.dir || 'ltr';

  // Update Language dropdown UI labels
  const currentLangLabel = document.getElementById('currentLangLabel');
  if (currentLangLabel) {
    currentLangLabel.innerHTML = `<span class="mr-1.5 text-base">${langConfig.flag}</span> <span class="font-bold">${langConfig.code.toUpperCase()}</span>`;
  }

  // Update all [data-i18n] elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translation = t(key);
    if (translation) {
      el.innerHTML = translation;
    }
  });

  // Update all [data-i18n-placeholder] elements
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const translation = t(key);
    if (translation) {
      el.setAttribute('placeholder', translation);
    }
  });

  // Re-render chat welcome message if chat history has only initial message
  updateChatWelcomeMessage();

  // If tour packages are currently visible on screen, re-render them to update labels
  if (typeof currentPackages !== 'undefined' && currentPackages && currentPackages.length > 0) {
    if (typeof renderCreativeTourPackages === 'function') {
      renderCreativeTourPackages(currentPackages);
    }
  }

  // Close dropdown if open
  const dropdown = document.getElementById('langDropdownMenu');
  if (dropdown) dropdown.classList.add('hidden');
}

/**
 * Initialize Language Selector and apply default translations
 */
function initI18n() {
  const initialLang = getCurrentLang();
  buildLanguageSelector();
  setLanguage(initialLang);
}

